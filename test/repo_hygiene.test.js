/**
 * Repository hygiene, enforced by the suite so a slip is caught before packaging.
 *
 * Sweeps tracked and untracked files (git ls-files --cached --others --exclude-standard), so
 * a file that is not yet committed cannot exempt itself.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync, existsSync } from "node:fs";
import { join, extname } from "node:path";
import { FIXTURE } from "./helpers.js";

const ROOT = join(FIXTURE, "..");
const REPO = "ManojKumarChunduru/crm-sync-referee";
const AUTHOR = "Manoj Kumar Chunduru <hello.manojchunduru@gmail.com>";

function git(...args) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" });
}

const TEXT_EXTENSIONS = new Set([".js", ".json", ".md", ".yml", ".yaml", ".xml", ".cls", ".trigger", ".svg", ".txt", ".html", ".css", ""]);

function textFiles() {
  const listed = git("ls-files", "--cached", "--others", "--exclude-standard").split("\n").filter(Boolean);
  return listed.filter((p) => TEXT_EXTENSIONS.has(extname(p)) && existsSync(join(ROOT, p))
    && !p.startsWith("node_modules/") && p !== "package-lock.json");
}

// The patterns below are assembled from parts so this file does not match its own sweep.
const PLACEHOLDERS = new RegExp(["your", "-handle", "|YOUR", "_HANDLE|<", "handle>|example@", "example|your", "name"].join(""), "i");

const EM_DASH = String.fromCodePoint(0x2014);
const EN_DASH = String.fromCodePoint(0x2013);

test("no tracked or untracked text file contains an em dash or an en dash", () => {
  const offenders = [];
  for (const path of textFiles()) {
    const text = readFileSync(join(ROOT, path), "utf8");
    if (text.includes(EM_DASH) || text.includes(EN_DASH)) offenders.push(path);
  }
  assert.deepEqual(offenders, []);
});

test("every commit is authored by the candidate alone, with no trailers and no tool name", () => {
  const authors = new Set(git("log", "--format=%an <%ae>").split("\n").filter(Boolean));
  assert.deepEqual([...authors], [AUTHOR]);
  const bodies = git("log", "--format=%B");
  for (const needle of ["Co-Authored-By", "Co-authored-by", "Generated-By", "Session-Id", "Claude", "Anthropic", "ChatGPT", "Copilot"]) {
    assert.ok(!bodies.includes(needle), `commit messages mention ${needle}`);
  }
});

test("no file mentions an AI tool as an author or generator", () => {
  const offenders = [];
  const pattern = /(Co-Authored-By|Generated by|Generated with)[^\n]*(Claude|Anthropic|ChatGPT|Copilot)/i;
  for (const path of textFiles()) {
    if (path.startsWith("test/")) continue;
    if (pattern.test(readFileSync(join(ROOT, path), "utf8"))) offenders.push(path);
  }
  assert.deepEqual(offenders, []);
});

test("no placeholder handle or placeholder email is left anywhere", () => {
  const offenders = [];
  for (const path of textFiles()) {
    const text = readFileSync(join(ROOT, path), "utf8");
    if (PLACEHOLDERS.test(text)) offenders.push(path);
  }
  assert.deepEqual(offenders, []);
});

test("every GitHub URL names this repository exactly", () => {
  const offenders = [];
  for (const path of textFiles()) {
    const text = readFileSync(join(ROOT, path), "utf8");
    for (const match of text.matchAll(/github\.com\/([\w.-]+\/[\w.-]+)/g)) {
      const repo = match[1].replace(/\.git$/, "");
      if (repo !== REPO) offenders.push(`${path}: ${repo}`);
    }
  }
  assert.deepEqual(offenders, []);
});

test("the package metadata names the candidate and the repository", () => {
  const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  assert.equal(pkg.author, AUTHOR);
  assert.equal(pkg.repository.url, `https://github.com/${REPO}.git`);
  assert.deepEqual(pkg.dependencies, {});
});

test("the LICENSE names the candidate", () => {
  assert.match(readFileSync(join(ROOT, "LICENSE"), "utf8"), /Copyright \(c\) 2026 Manoj Kumar Chunduru/);
});

test("no document quotes a measured duration as a figure; a declared tolerance or a planted gap is not a measurement", () => {
  // This repository's subject includes time: the clock skew tolerance is a policy in the contract and the
  // fixture plants writes a known number of seconds apart. Those are inputs, not timings of this machine, and
  // every one sits on a line that names the tolerance, the skew, the clock or the gap. Anything else that
  // reads as a duration (a millisecond, a runtime in seconds) is still refused.
  const offenders = [];
  const docs = textFiles().filter((p) => p.endsWith(".md") && !p.startsWith("node_modules/"));
  const declared = /\b(tolerance|skew|clock|apart|gap)\b/i;
  for (const path of docs) {
    const text = readFileSync(join(ROOT, path), "utf8").replace(/```[\s\S]*?```/g, "");
    for (const line of text.split("\n")) {
      const m = /\b\d+(\.\d+)?\s?(ms|milliseconds|seconds|secs|minutes)\b/i.exec(line);
      if (m === null) continue;
      if (/\b(ms|milliseconds|minutes|secs)\b/i.test(m[0]) || !declared.test(line)) offenders.push(`${path}: ${m[0]}`);
    }
  }
  assert.deepEqual(offenders, []);
});
